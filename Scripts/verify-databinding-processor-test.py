#!/usr/bin/env python3
"""실제 AGP DataBinding 회귀가 생략 없이 실행된 JUnit 근거를 보존한다."""
import hashlib
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SUITE = "dev.kartograph.gradle.AndroidDataBindingIntegrationTest"
CASE = "실제 DataBinding 생성 호출은 overload와 variant를 구분하고 도달하지 않은 owner를 살리지 않는다(Path)"
MARKERS = (
    "data-binding-native debugCalls=",
    "data-binding-native releaseCalls=",
    "data-binding-native uncalledOwner=class:p/databinding/ScreenBindingImpl reachable=false compiledCallsPreserved=true",
)


def verify(directory):
    source = directory / f"TEST-{SUITE}.xml"
    raw = source.read_bytes()
    suite = ET.fromstring(raw)
    if suite.tag != "testsuite" or suite.get("name") != SUITE or suite.get("tests") != "1":
        raise ValueError("required DataBinding processor suite is absent or unexpected")
    if any(suite.get(key) != "0" for key in ("skipped", "failures", "errors")):
        raise ValueError("DataBinding processor test was skipped or failed")
    cases = suite.findall("testcase")
    if len(cases) != 1 or cases[0].get("name") != CASE or cases[0].get("classname") != SUITE:
        raise ValueError("required DataBinding processor case is absent or duplicated")
    if any(cases[0].find(tag) is not None for tag in ("skipped", "failure", "error")):
        raise ValueError("required DataBinding processor case did not pass")
    lines = (suite.findtext("system-out") or "").splitlines()
    observations = []
    for marker in MARKERS:
        matches = [line for line in lines if line.startswith(marker)]
        if len(matches) != 1:
            raise ValueError("DataBinding generated-call observation absent or duplicated")
        observations.append(matches[0])
    return dict(suite=SUITE, case=CASE, executed=1, skipped=0, failures=0, errors=0,
                xmlSha256=hashlib.sha256(raw).hexdigest(), observations=observations,
                scope="Actual AGP-generated bytecode and static paths, not device runtime or private application validation")


def main():
    result = verify(ROOT / "gradle-plugin/build/test-results/test")
    result["commit"] = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    target = ROOT / "build/reports/databinding-processor-test.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
